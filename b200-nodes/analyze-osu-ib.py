#!/usr/bin/env python3
"""Analyze OSU MPI p2p + raw InfiniBand pair runs and write out-osu-ib/summary.md.

Reads every out-osu-ib/osu-ib-<nodeA>-<nodeB>-<jobid>.out written by
job-osu-ib-pair.sh (newest run per pair wins) and writes one row per node pair.
Pairs listed in out-osu-ib/pairs.txt that have no finished run yet are listed
as pending. Each pair job calls this at its end, so the summary fills in as
jobs finish. Plain Python 3.6 (the compute nodes' python3).
"""
import glob
import os
import re
import time

OUT_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out-osu-ib")
SIZE = 64 * 1024 * 1024
LINE_RATE = 400.0          # NDR Gb/s per rail


def sections(text):
    secs, cur = {}, None
    for line in text.splitlines():
        if line.startswith("=== "):
            cur = line[4:].split()[0]
            secs[cur] = []
        elif cur:
            secs[cur].append(line)
    return secs


def rows(lines, ncol):
    out = []
    for l in lines:
        f = l.split()
        if len(f) >= ncol and all(re.match(r"^[0-9.]+$", x) for x in f[:ncol]):
            out.append([float(x) for x in f])
    return out


def field(lines, key):
    for l in lines:
        if l.startswith(key):
            return l.split(":", 1)[1].strip()
    return None


def parse(path):
    text = open(path, errors="replace").read()
    s = sections(text)
    info = s.get("info", [])
    nodes = (field(info, "nodes") or "").split()
    if len(nodes) != 2:
        return None
    r = {"file": os.path.basename(path), "pair": tuple(nodes),
         "job": field(info, "job"), "date": field(info, "date"),
         "mtime": os.path.getmtime(path), "done": "done" in s,
         "hosts": [l.split(":", 1)[1].strip() for l in info if l.startswith("host")],
         "sharing": field(info, "sharing"), "ompi": field(info, "ompi"),
         "errors": []}
    lat = rows(s.get("osu_latency", []), 2)
    r["lat"] = next((v[1] for v in lat if v[0] == 8), None)
    for b in ("osu_bw", "osu_bibw"):
        d = rows(s.get(b, []), 2)
        r[b] = max((v[1] for v in d), default=None) if d else None
    bw = [v for v in rows(s.get("ib_write_bw", []), 4) if v[0] == SIZE]
    r["ibbw"] = bw[-1][3] if bw else None
    lt = [v for v in rows(s.get("ib_write_lat", []), 7) if v[0] == 2]
    r["iblat"] = lt[-1][4] if lt else None
    r["iblat_min"] = lt[-1][2] if lt else None
    for b, k in (("osu_latency", "lat"), ("osu_bw", "osu_bw"), ("osu_bibw", "osu_bibw"),
                 ("ib_write_bw", "ibbw"), ("ib_write_lat", "iblat")):
        if r[k] is None:
            msg = [l.strip() for l in s.get(b, []) if re.search(r"error|fail|abort|unable|timeout|refused", l, re.I)]
            r["errors"].append("%s: %s" % (b, msg[0][:160] if msg else ("not run" if b not in s else "no result")))
    abort = [l.strip() for l in info if "FAIL" in l]
    if abort:                      # preflight / lock failure: nothing was measured
        r["errors"] = abort
    return r


def fmt(v, spec="%.2f"):
    return "—" if v is None else spec % v


def main():
    runs = {}
    for f in sorted(glob.glob(os.path.join(OUT_DIR, "osu-ib-*.out")), key=os.path.getmtime):
        r = parse(f)
        if r:
            runs[r["pair"]] = r
    pairs = []
    pf = os.path.join(OUT_DIR, "pairs.txt")
    if os.path.exists(pf):
        pairs = [tuple(sorted(l.split())) for l in open(pf) if len(l.split()) == 2]

    md = ["# OSU MPI point-to-point + raw InfiniBand between B200 nodes", "",
          "- Updated: %s (regenerated by `analyze-osu-ib.py` at the end of every pair job)" % time.strftime("%Y-%m-%d %H:%M:%S"),
          "- Jobs: `job-osu-ib-pair.sh` (one pair per job), sweep via `submit-osu-ib-sweep.sh`; partition `mit_testing`, no QoS set",
          "- OSU Micro-Benchmarks 7.5-1 (`../mpi-p2p/install/r8-4.1.4`), default `openmpi/4.1.4` module (gcc/12.2.0), "
          "1 rank per node, host memory, no MCA/UCX tuning (Open MPI picks transport and NIC)",
          "- Raw IB: perftest `ib_write_bw` (64 MiB, 200 iterations, host mem -> host mem, `--report_gbits`) and "
          "`ib_write_lat` (2 B, 10000 iterations) on `mlx5_4`",
          "- Reference: NDR line rate 400 Gb/s = 50 GB/s per rail. OSU bandwidth is one MPI pair, so it is bounded by one rail.",
          "- Jobs are not `--exclusive`: other users' jobs may share the nodes (column *others*), and their traffic can add noise. "
          "Two pair jobs of this sweep never test on the same node at the same time (node-local lock).", ""]

    ok = [r for r in runs.values() if not r["errors"] and r["done"]]
    md += ["## Status", "",
           "- Pairs finished: **%d** (%d fully OK, %d with a failed test)%s" % (
               len(runs), len(ok), len(runs) - len(ok),
               (", %d pending of %d in the sweep" % (len([p for p in pairs if p not in runs]), len(pairs))) if pairs else ""),
           ""]
    if runs:
        def rng(k):
            v = [r[k] for r in ok if r[k] is not None]
            return (min(v), max(v)) if v else (None, None)
        lo, hi = rng("lat"); md.append("- OSU latency 8 B: %s–%s µs" % (fmt(lo), fmt(hi)))
        lo, hi = rng("osu_bw"); md.append("- OSU bw peak: %s–%s GB/s" % (fmt(lo and lo / 1000), fmt(hi and hi / 1000)))
        lo, hi = rng("osu_bibw"); md.append("- OSU bibw peak: %s–%s GB/s" % (fmt(lo and lo / 1000), fmt(hi and hi / 1000)))
        lo, hi = rng("ibbw"); md.append("- ib_write_bw 64 MiB: %s–%s Gb/s (%s–%s%% of 400 Gb/s)" % (
            fmt(lo, "%.1f"), fmt(hi, "%.1f"), fmt(lo and 100 * lo / LINE_RATE, "%.0f"), fmt(hi and 100 * hi / LINE_RATE, "%.0f")))
        lo, hi = rng("iblat"); md.append("- ib_write_lat 2 B typical: %s–%s µs" % (fmt(lo), fmt(hi)))
        md.append("")

    md += ["## Results by node pair", "",
           "| Pair | Job | Date | OSU lat 8 B (µs) | OSU bw peak (GB/s) | OSU bibw peak (GB/s) | ib_write_bw 64 MiB (Gb/s) | ib_write_lat 2 B typ / min (µs) | others | Status |",
           "|---|---|---|---:|---:|---:|---:|---:|---:|---|"]
    for p in sorted(runs):
        r = runs[p]
        st = "OK" if (not r["errors"] and r["done"]) else ("FAIL" if r["done"] else "incomplete")
        others = (r["sharing"] or "").split()[0] if r["sharing"] else "—"
        md.append("| %s + %s | %s | %s | %s | %s | %s | %s | %s / %s | %s | %s |" % (
            p[0], p[1], r["job"], r["date"], fmt(r["lat"]),
            fmt(r["osu_bw"] and r["osu_bw"] / 1000), fmt(r["osu_bibw"] and r["osu_bibw"] / 1000),
            fmt(r["ibbw"], "%.1f"), fmt(r["iblat"]), fmt(r["iblat_min"]), others, st))
    md.append("")

    bad = [r for r in runs.values() if r["errors"] or not r["done"]]
    if bad:
        md += ["## Failures", ""]
        for r in sorted(bad, key=lambda x: x["pair"]):
            md.append("- **%s + %s** (job %s, `%s`): %s" % (r["pair"][0], r["pair"][1], r["job"], r["file"],
                                                         "; ".join(r["errors"]) or "job did not reach the end"))
        md.append("")
    pend = [p for p in pairs if p not in runs]
    if pend:
        md += ["## Pending pairs", "", ", ".join("%s+%s" % p for p in pend), ""]
    if runs:
        md += ["## Node configuration seen in the runs", ""]
        hosts = {}
        for r in runs.values():
            for h in r["hosts"]:
                hosts[h.split("|")[0].strip()] = h
        for h in sorted(hosts):
            md.append("- %s" % hosts[h])
        md.append("")
        md.append("Raw output: `out-osu-ib/osu-ib-*.out`, perftest server/client logs in `out-osu-ib/raw/<job>/`.")
        md.append("")

    tmp = os.path.join(OUT_DIR, ".summary.md.%d" % os.getpid())
    with open(tmp, "w") as fh:
        fh.write("\n".join(md))
    os.replace(tmp, os.path.join(OUT_DIR, "summary.md"))


if __name__ == "__main__":
    main()
